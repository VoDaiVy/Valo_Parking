const test = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const Entitlement = require('../models/MembershipSlotEntitlement');
const Renewal = require('../models/MembershipEntitlementRenewal');
const Vehicle = require('../models/Vehicle');
const Floor = require('../models/ParkingFloor');
const Slot = require('../models/Slot');
const Subscription = require('../models/Subscription');
const projection = require('../services/membershipProjectionService');
const notifications = require('../services/membershipNotifications');
const payosPath = require.resolve('../config/payos');
const originalPayos = require.cache[payosPath];
let paymentStatus = 'PENDING';
require.cache[payosPath] = { id: payosPath, filename: payosPath, loaded: true, exports: { paymentRequests: { get: async () => ({ status: paymentStatus }) } } };
const originalProjection = projection.recomputeUserMembership;
projection.recomputeUserMembership = async () => {};
const renewalService = require('../services/membershipEntitlementRenewalService');
projection.recomputeUserMembership = originalProjection;
if (originalPayos) require.cache[payosPath] = originalPayos; else delete require.cache[payosPath];

test('real entitlement verify with fixtures notifies only after expiry update and commit; replay/pending/failed do not emit success', async (t) => {
  t.mock.timers.enable({ apis: ['Date'], now: new Date('2026-10-20T03:00:00Z') });
  const original = [Floor.findById, Slot.findById, Renewal.findOne, Renewal.findById, Entitlement.findOne, Entitlement.findOneAndUpdate, Entitlement.countDocuments, Vehicle.countDocuments, Slot.updateOne, Subscription.updateOne, mongoose.startSession, notifications.notifyRenewal];
  const userId = '507f1f77bcf86cd799439011';
  const id = '507f1f77bcf86cd799439012';
  const oldExpireAt = new Date('2026-10-22T03:00:00Z');
  const newExpireAt = new Date('2026-11-22T03:00:00Z');
  const entitlement = { _id: id, ownerId: userId, expireAt: oldExpireAt, slotCode: 'M1', sourceSubscriptionId: id, slotId: id, floorId: id, packageId: { name: 'Premium Monthly', type: 'monthly', price: 100000, renewalWindowDays: 7 } };
  const row = { _id: id, userId, entitlementId: id, status: 'pending', amount: 100000, oldExpireAt, newExpireAt, save: async () => {} };
  let committed = false;
  let commitFails = false;
  let successCount = 0;
  const query = (value) => ({ select() { return this; }, session() { return this; }, then(resolve, reject) { return Promise.resolve(value).then(resolve, reject); } });
  Floor.findById = () => query({ layoutData: { elements: [{ type: 'slot', name: 'M1' }] } });
  Slot.findById = () => query({ floorID: id, slotNumber: 'M1', reservedFor: userId, reservedByEntitlementId: id, reservedBySubscriptionId: id });
  Renewal.findOne = async () => row;
  Renewal.findById = () => ({ session: async () => row });
  Entitlement.findOne = () => ({ populate: async () => entitlement });
  Entitlement.findOneAndUpdate = async (filter, update) => { assert.equal(filter.expireAt, oldExpireAt); entitlement.expireAt = update.$set.expireAt; return entitlement; };
  Entitlement.countDocuments = Vehicle.countDocuments = async () => 1;
  Slot.updateOne = async () => ({ matchedCount: 1 });
  Subscription.updateOne = async () => {};
  mongoose.startSession = async () => ({ startTransaction() {}, async commitTransaction() { if (commitFails) throw new Error('fixture commit failed'); committed = true; }, async abortTransaction() { row.status = 'pending'; entitlement.expireAt = oldExpireAt; }, async endSession() {} });
  notifications.notifyRenewal = async (record) => { assert.equal(committed, true); assert.equal(record.status, 'paid'); assert.equal(record.notificationPending, true); assert.equal(entitlement.expireAt.toISOString(), newExpireAt.toISOString()); successCount += 1; };
  const verify = () => renewalService.verifyPayosRenewal({ userId, orderCode: 123456 });
  try {
    await assert.rejects(verify(), (error) => error.code === 'PAYMENT_NOT_COMPLETED');
    assert.equal(successCount, 0);
    paymentStatus = 'FAILED';
    await assert.rejects(verify(), (error) => error.code === 'PAYMENT_NOT_COMPLETED');
    assert.equal(row.status, 'failed');
    assert.equal(successCount, 0);
    row.status = 'pending'; paymentStatus = 'PAID'; commitFails = true;
    await assert.rejects(verify(), /commit failed/);
    assert.equal(successCount, 0);
    assert.equal(entitlement.expireAt, oldExpireAt);
    commitFails = false;
    assert.equal((await verify()).alreadyProcessed, false);
    assert.equal(successCount, 1);
    assert.equal((await verify()).alreadyProcessed, true);
    assert.equal(successCount, 1);
  } finally { [Floor.findById, Slot.findById, Renewal.findOne, Renewal.findById, Entitlement.findOne, Entitlement.findOneAndUpdate, Entitlement.countDocuments, Vehicle.countDocuments, Slot.updateOne, Subscription.updateOne, mongoose.startSession, notifications.notifyRenewal] = original; }
});
